package eu.vendeli

import eu.vendeli.tgbot.implementations.ClassManagerImpl
import io.kotest.core.spec.style.AnnotationSpec
import io.kotest.matchers.collections.shouldBeEmpty
import io.kotest.matchers.collections.shouldNotBeEmpty
import io.kotest.matchers.shouldBe
import kotlinx.serialization.InternalSerializationApi
import kotlinx.serialization.PolymorphicSerializer
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.serializerOrNull
import java.io.File
import java.util.jar.JarFile

/**
 * Ratchet over the GraalVM metadata shipped in the jvm jar under `META-INF/native-image/eu.vendeli/telegram-bot`.
 * Each failure names a class that would fail at runtime in a native image:
 * - generated by `generateNativeImageMetadata`: every class kotlinx.serialization can resolve from a `KClass`
 * - static `kotlin-reflect/`: what kotlin-reflect itself looks up reflectively (re-check it on kotlin-reflect updates)
 */
class NativeImageMetadataTest : AnnotationSpec() {
    private val generated by lazy { readJson("$BASE/reachability-metadata.json").jsonObject }
    private val kotlinReflect by lazy { readJson("$BASE/kotlin-reflect/reachability-metadata.json").jsonObject }

    @Test
    fun `generated metadata registers serializer lookups`() {
        generated.reflection().keys.shouldNotBeEmpty()
    }

    @OptIn(InternalSerializationApi::class)
    @Test
    fun `every class resolvable from a KClass is registered`() {
        val classesDir = File(
            ClassManagerImpl::class.java.protectionDomain.codeSource.location
                .toURI(),
        )
        classesDir.isDirectory shouldBe true

        val registered = generated.reflection().keys
        val loader = javaClass.classLoader
        val problems = classesDir
            .walkTopDown()
            .filter { it.extension == "class" }
            .map {
                it
                    .relativeTo(classesDir)
                    .path
                    .removeSuffix(".class")
                    .replace(File.separatorChar, '.')
            }.mapNotNull { name ->
                // A class that can't be loaded or looked up is reported, not skipped: it could hide a gap.
                val cls = runCatching { Class.forName(name, false, loader) }
                    .getOrElse { return@mapNotNull "cannot load $name: $it" }
                val serializer = runCatching { cls.kotlin.serializerOrNull() }
                    .getOrElse { return@mapNotNull "lookup failed for $name: $it" }
                // Polymorphic serializers are built from annotations only, without member lookups.
                if (serializer != null && serializer !is PolymorphicSerializer<*> && name !in registered) {
                    "not registered: $name"
                } else {
                    null
                }
            }.sorted()
            .toList()

        problems.shouldBeEmpty()
    }

    @Test
    fun `no type is registered twice`() {
        listOf(generated, kotlinReflect)
            .flatMap { metadata ->
                metadata
                    .reflectionEntries()
                    .groupingBy { it.type() }
                    .eachCount()
                    .filterValues { it > 1 }
                    .keys
            }.shouldBeEmpty()
    }

    @Test
    fun `legacy files register the same entries`() {
        // Same entries, members included; only the type key differs ("name" instead of "type").
        val pairs = listOf(
            generated to readJson("$BASE/reflect-config.json").jsonArray,
            kotlinReflect to readJson("$BASE/kotlin-reflect/reflect-config.json").jsonArray,
        )
        pairs
            .flatMap { (current, legacy) ->
                val currentEntries = current.reflectionEntries().map { it.withTypeKey("name") }.toSet()
                val legacyEntries = legacy.map { it.jsonObject }.toSet()
                (legacyEntries - currentEntries).map { "only legacy: $it" } +
                    (currentEntries - legacyEntries).map { "only current: $it" }
            }.shouldBeEmpty()
    }

    @Test
    fun `kotlin-reflect factory is registered`() {
        kotlinReflect.reflection()[REFLECTION_FACTORY]?.hasNoArgConstructor() shouldBe true
    }

    @Test
    fun `kotlin-reflect service providers are registered`() {
        val resources = kotlinReflect.resourceGlobs()
        val reflection = kotlinReflect.reflection()
        val problems = mutableListOf<String>()

        JarFile(
            File(
                Class
                    .forName(REFLECTION_FACTORY)
                    .protectionDomain.codeSource.location
                    .toURI(),
            ),
        ).use { jar ->
            jar
                .entries()
                .asSequence()
                .filter { !it.isDirectory && it.name.startsWith("META-INF/services/") }
                .forEach { entry ->
                    if (entry.name !in resources) problems += "resource ${entry.name}"
                    jar
                        .getInputStream(entry)
                        .bufferedReader()
                        .readLines()
                        .map { it.substringBefore('#').trim() }
                        .filter { it.isNotEmpty() }
                        .filter { reflection[it]?.hasNoArgConstructor() != true }
                        .forEach { problems += "provider $it" }
                }
        }

        problems.shouldBeEmpty()
    }

    @Test
    fun `kotlin-reflect resources are included by both formats`() {
        // Every service file of kotlin-reflect and every .kotlin_builtins file it loads (they live in kotlin-stdlib)
        // must match a glob of the current format and a regex of the legacy resource-config.json.
        val globs = kotlinReflect.resourceGlobs().map(::globToRegex)
        val legacyPatterns = readJson("$BASE/kotlin-reflect/resource-config.json")
            .jsonObject
            .getValue("resources")
            .jsonObject
            .getValue("includes")
            .jsonArray
            .map {
                Regex(
                    it.jsonObject
                        .getValue("pattern")
                        .jsonPrimitive.content,
                )
            }

        val resources = jarEntries(Class.forName(REFLECTION_FACTORY))
            .filter { it.startsWith("META-INF/services/") && !it.endsWith("/") } +
            jarEntries(Unit::class.java).filter { it.endsWith(".kotlin_builtins") }
        // Guards against checking nothing, e.g. if the files move to another jar.
        resources.any { it.startsWith("META-INF/services/") } shouldBe true
        resources.any { it.endsWith(".kotlin_builtins") } shouldBe true

        resources
            .flatMap { name ->
                listOfNotNull(
                    "no glob for $name".takeIf { globs.none { it.matches(name) } },
                    "no legacy pattern for $name".takeIf { legacyPatterns.none { it.matches(name) } },
                )
            }.shouldBeEmpty()
    }

    /** Entry names of the jar that contains [cls]. */
    private fun jarEntries(cls: Class<*>): List<String> =
        JarFile(
            File(
                cls.protectionDomain.codeSource.location
                    .toURI(),
            ),
        ).use { jar ->
            jar
                .entries()
                .asSequence()
                .map { it.name }
                .toList()
        }

    /** GraalVM resource glob to regex: `**` spans directories, `*` stays within one. */
    private fun globToRegex(glob: String): Regex = Regex(
        glob
            .split("**/")
            .joinToString("(?:.*/)?") { part ->
                part.split("*").joinToString("[^/]*") { Regex.escape(it) }
            },
    )

    @Test
    fun `kotlin-reflect built-in type map is registered`() {
        // kotlin-reflect probes both names of every mapped built-in type (kotlin.Int and java.lang.Integer).
        (kotlinBuiltInTypeMap() - kotlinReflect.reflection().keys).sorted().shouldBeEmpty()
    }

    private fun readJson(path: String): JsonElement {
        val resource = requireNotNull(javaClass.classLoader.getResource(path)) { "$path is not on the classpath" }
        return Json.parseToJsonElement(resource.readText())
    }

    private fun JsonObject.reflectionEntries(): List<JsonObject> = getValue(
        "reflection",
    ).jsonArray.map { it.jsonObject }

    private fun JsonObject.type(): String = getValue("type").jsonPrimitive.content

    private fun JsonObject.withTypeKey(key: String): JsonObject =
        JsonObject(entries.associate { (k, v) -> (if (k == "type") key else k) to v })

    /** Entries by type; `no type is registered twice` guarantees this loses nothing. */
    private fun JsonObject.reflection(): Map<String, JsonObject> = reflectionEntries().associateBy { it.type() }

    private fun JsonObject.resourceGlobs(): Set<String> = getValue("resources")
        .jsonArray
        .map {
            it.jsonObject
                .getValue("glob")
                .jsonPrimitive.content
        }.toSet()

    private fun JsonObject.hasNoArgConstructor(): Boolean = (this["methods"] as? JsonArray).orEmpty().any {
        it.jsonObject
            .getValue("name")
            .jsonPrimitive.content == "<init>" &&
            it.jsonObject
                .getValue("parameterTypes")
                .jsonArray
                .isEmpty()
    }

    /** Class names from kotlin-reflect's internal JavaToKotlinClassMap, as JVM binary names. */
    private fun kotlinBuiltInTypeMap(): Set<String> {
        val map = Class.forName("kotlin.reflect.jvm.internal.impl.builtins.jvm.JavaToKotlinClassMap")
        val classIds = listOf("javaToKotlin", "kotlinToJava")
            .flatMap { name ->
                (map.getDeclaredField(name).apply { isAccessible = true }.get(null) as Map<*, *>).values
            }.toMutableList()
        val instance = map.getField("INSTANCE").get(null)
        (map.getMethod("getMutabilityMappings").invoke(instance) as List<*>).forEach { mapping ->
            listOf("getJavaClass", "getKotlinReadOnly", "getKotlinMutable").forEach {
                classIds += mapping!!.javaClass.getMethod(it).invoke(mapping)
            }
        }
        return classIds
            .map { id ->
                val pkg = id!!
                    .javaClass
                    .getMethod("getPackageFqName")
                    .invoke(id)
                    .toString()
                val relative = id.javaClass
                    .getMethod("getRelativeClassName")
                    .invoke(id)
                    .toString()
                    .replace('.', '$')
                if (pkg.isEmpty()) relative else "$pkg.$relative"
            }.toSet()
    }

    private companion object {
        const val BASE = "META-INF/native-image/eu.vendeli/telegram-bot"
        const val REFLECTION_FACTORY = "kotlin.reflect.jvm.internal.ReflectionFactoryImpl"
    }
}
